export function turkeyRegionCollection() {
  return {
    type: 'FeatureCollection' as const,
    features: TURKEY_REGIONS.map((region) => ({
      type: 'Feature' as const,
      properties: { id: region.id },
      geometry: {
        type: 'Polygon' as const,
        coordinates: [region.ring],
      },
    })),
  }
}

export function regionById(id: string | null) {
  return TURKEY_REGIONS.find((item) => item.id === id) ?? null
}
